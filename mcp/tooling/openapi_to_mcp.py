"""OpenAPI-to-MCP conversion CLI.

Generates a standalone FastMCP server scaffold from an OpenAPI spec and
a YAML allowlist config. The generated scaffold uses FastMCP.from_openapi()
with RouteMap filtering and includes a ConfigMap file-watcher for live
backend URL switching (BACK-03 compliance).

Usage:
    openapi-to-mcp --spec <spec.yaml> --allowlist <allowlist.yaml> [--output server.py]

Design decisions:
    - D-11: Generic CLI at mcp/tooling/openapi_to_mcp.py
    - D-12: YAML allowlist config with RouteMap filtering
    - D-13: One-time codegen, then hand-curate
    - D-16: ConfigMap file-watcher baked into generated scaffolds
    - Uses string.Template ($var substitution) to avoid brace-escaping
      issues with Python dict literals, f-strings, and set syntax in
      the generated code (addresses Gemini HIGH review finding).
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from datetime import datetime, timezone
from pathlib import Path
from string import Template

from allowlist_schema import load_allowlist


# ---------------------------------------------------------------------------
# Scaffold template (string.Template with $var substitution)
# ---------------------------------------------------------------------------

SCAFFOLD_TEMPLATE = Template(textwrap.dedent('''\
    # Auto-generated by mcp/tooling/openapi_to_mcp.py
    # Spec: $spec_filename
    # Allowlist: $allowlist_filename
    # Generated: $generation_timestamp
    #
    # CURATION GUIDE:
    # 1. Edit descriptions in customize_components() for LLM clarity
    # 2. Adjust route_maps to include/exclude operations
    # 3. For full control, replace from_openapi() with explicit @mcp.tool() decorators
    # 4. DO NOT edit the ConfigMap watcher section (ConfigMap contract, BACK-03)

    import os
    import json
    import threading
    import time
    from pathlib import Path
    from fastmcp import FastMCP
    from fastmcp.server.providers.openapi import RouteMap, MCPType, OpenAPITool
    import httpx2
    import yaml


    # --- ConfigMap file-watcher (BACK-03 contract) ---
    BACKEND_ROUTING_PATH = os.environ.get(
        "BACKEND_ROUTING_FILE", "/config/backend-routing/$backend_env_var"
    )
    _backend_url_lock = threading.Lock()
    _backend_url = "http://localhost:4010"  # default fallback


    def _load_backend_url():
        """Read backend URL from ConfigMap-mounted file and update state.

        Validates URL starts with http:// or https:// (T-02-04 mitigation).
        On valid URL: updates _backend_url under lock AND mutates client.base_url.
        On invalid URL: keeps previous valid URL.
        """
        global _backend_url
        try:
            url = Path(BACKEND_ROUTING_PATH).read_text().strip()
            if url and (url.startswith("http://") or url.startswith("https://")):
                with _backend_url_lock:
                    _backend_url = url
                client.base_url = url
                # TODO(Phase 3): Validate that FastMCP from_openapi() re-reads client.base_url
                # per-request. If it freezes the URL at tool-construction time, the alternative
                # is to recreate the FastMCP app instance on backend-URL change.
                # See .planning/STATE.md and 02-RESEARCH.md Open Question 1.
        except FileNotFoundError:
            pass  # use default on first boot


    def get_backend_url() -> str:
        """Return current backend URL under lock."""
        with _backend_url_lock:
            return _backend_url


    def _start_config_watcher():
        """Poll ConfigMap-mounted file for changes (mtime-based).

        Uses mtime polling instead of inotify because Kubernetes
        updates ConfigMap volumes via atomic symlink swaps, which
        do not emit standard IN_MODIFY events.
        """
        config_path = Path(BACKEND_ROUTING_PATH)
        last_mtime = 0.0

        def _poll():
            nonlocal last_mtime
            while True:
                try:
                    current_mtime = config_path.stat().st_mtime
                    if current_mtime != last_mtime:
                        last_mtime = current_mtime
                        _load_backend_url()
                except FileNotFoundError:
                    pass
                time.sleep(5)  # poll every 5 seconds

        t = threading.Thread(target=_poll, daemon=True)
        t.start()


    # --- OpenAPI Server ---
    SPEC_PATH = Path("$spec_path")

    route_maps = [
    $route_maps_code
        # Exclude everything else (catch-all)
        RouteMap(mcp_type=MCPType.EXCLUDE),
    ]


    def customize_components(route, component):
        """Customize tool descriptions for LLM consumption.

        Phase 3: improve these descriptions for telecom domain clarity.
        """
        if isinstance(component, OpenAPITool):
            # Edit descriptions, add tags, adjust parameters here
            pass


    spec_dict = yaml.safe_load(SPEC_PATH.read_text())
    client = httpx2.AsyncClient(base_url=get_backend_url())

    mcp = FastMCP.from_openapi(
        openapi_spec=spec_dict,
        client=client,
        route_maps=route_maps,
        mcp_component_fn=customize_components,
    )

    # --- Startup ---
    _load_backend_url()
    _start_config_watcher()

    if __name__ == "__main__":
        mcp.run(transport="http", host="0.0.0.0", port=8000, stateless_http=True)
'''))


def _build_route_maps_code(operations: list) -> str:
    """Generate RouteMap entries from allowlist operations.

    RouteMap uses `pattern` (a regex) for path matching, not a `path`
    keyword. We convert the allowlist's `path` field (e.g. "/verify")
    into a regex pattern that matches routes containing that path
    (e.g. r"/verify").
    """
    lines = []
    for op in operations:
        methods_str = repr(op.methods)
        # Escape the path for use in regex, then use as pattern
        # RouteMap pattern is matched against the route path
        import re as _re
        escaped = _re.escape(op.path)
        lines.append(
            f'    RouteMap(pattern=r"{escaped}", methods={methods_str}, '
            f'mcp_type=MCPType.{op.mcp_type}),'
        )
    return "\n".join(lines)


def main():
    """CLI entry point for OpenAPI-to-MCP conversion."""
    parser = argparse.ArgumentParser(
        description="Generate a FastMCP server scaffold from an OpenAPI spec and allowlist config.",
        prog="openapi-to-mcp",
    )
    parser.add_argument(
        "--spec",
        required=True,
        help="Path to OpenAPI spec YAML/JSON file",
    )
    parser.add_argument(
        "--allowlist",
        required=True,
        help="Path to allowlist YAML config",
    )
    parser.add_argument(
        "--output",
        default="./server.py",
        help="Path for generated server.py (default: ./server.py)",
    )
    args = parser.parse_args()

    # 1. Load allowlist config
    allowlist = load_allowlist(args.allowlist)

    # 2. Verify spec file exists
    spec_file = Path(args.spec)
    if not spec_file.exists():
        print(f"Error: spec file not found: {args.spec}", file=sys.stderr)
        sys.exit(1)

    # 3. Resolve spec to absolute path (works from any directory)
    abs_spec_path = str(spec_file.resolve())

    # 4. Generate scaffold
    route_maps_code = _build_route_maps_code(allowlist.operations)
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    scaffold = SCAFFOLD_TEMPLATE.substitute(
        spec_path=abs_spec_path,
        server_name=allowlist.server_name,
        backend_env_var=allowlist.backend_env_var,
        route_maps_code=route_maps_code,
        generation_timestamp=now,
        spec_filename=spec_file.name,
        allowlist_filename=Path(args.allowlist).name,
    )

    # 5. Write generated scaffold
    output_path = Path(args.output)
    output_path.write_text(scaffold)

    # 6. Print summary
    total_ops = "unknown"  # Would need to parse the spec to count
    included = len(allowlist.operations)
    print(f"Generated MCP server scaffold:")
    print(f"  Spec: {spec_file.name}")
    print(f"  Server name: {allowlist.server_name}")
    print(f"  Operations included: {included}")
    print(f"  Output: {output_path}")


if __name__ == "__main__":
    main()
